Deno.serve(withCors(async (req) => {
  if (req.method === "OPTIONS") {
    return new Response(null, { headers: corsHeaders });
  }

  const __caller = await requireCaller(req);
  if (!__caller) return unauthorizedResponse(corsHeaders);


  try {
    const { email } = await req.json();

    // Rate limit: 3 per 5 minutes per email
    if (email && !checkRateLimit(`pwd:${email}`)) {
      return new Response(JSON.stringify({ error: "Rate limit exceeded" }), {
        status: 429,
        headers: { ...corsHeaders, "Content-Type": "application/json" },
      });
    }

    if (!email) {
      return new Response(JSON.stringify({ error: "Email is required" }), {
        status: 400,
        headers: { ...corsHeaders, "Content-Type": "application/json" },
      });
    }

    const resendApiKey = Deno.env.get("RESEND_API_KEY");
    const lovableApiKey = Deno.env.get("LOVABLE_API_KEY");
    if (!resendApiKey || !lovableApiKey) {
      throw new Error("RESEND_API_KEY or LOVABLE_API_KEY not configured");
    }

    const now = new Date();
    const dateStr = now.toLocaleDateString("ro-RO", {
      day: "2-digit",
      month: "long",
      year: "numeric",
      hour: "2-digit",
      minute: "2-digit",
    });

    const html = buildEmailTemplate({
      title: "Parola ta a fost schimbată",
      greeting: "Parola contului tău Rentli a fost schimbată cu succes. Dacă nu tu ai făcut această modificare, te rugăm să ne contactezi imediat.",
      rows: [
        { label: "Data schimbării", value: dateStr },
        { label: "Cont", value: escapeHtml(email) },
      ],
      ctaText: "Accesează contul",
      ctaLink: "/auth",
      footerText: "Ai primit acest email deoarece parola contului tău a fost schimbată.",
    });

    const resendRes = await fetch("https://connector-gateway.lovable.dev/resend/emails", {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        Authorization: `Bearer ${lovableApiKey}`,
        "X-Connection-Api-Key": resendApiKey,
      },
      body: JSON.stringify({
        from: "Rentli <noreply@rentli.ro>",
        to: [email],
        subject: "Parola ta a fost schimbată - Rentli",
        html,
      }),
    });

    if (!resendRes.ok) {
      const err = await resendRes.text();
      console.error("Resend gateway error:", err);
      throw new Error(`Resend gateway error ${resendRes.status}: ${err}`);
    }

    return new Response(JSON.stringify({ success: true }), {
      headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  } catch (error) {
    console.error("Error:", error);
    return new Response(JSON.stringify({ error: error.message }), {
      status: 500,
      headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  }
}, "POST, OPTIONS"));
